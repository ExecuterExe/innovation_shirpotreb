function startTimer(room, seconds, callback) {
    clearTimer(room);
    room.timerEnd = Date.now() + seconds * 1000;
    broadcastToRoom(room, {
        type: 'timerStart',
        duration: seconds,
        endsAt: room.timerEnd,
    });
    room.timer = setTimeout(() => {
        room.timer = null;
        callback();
    }, seconds * 1000);
}

function clearTimer(room) {
    if (room.timer) {
        clearTimeout(room.timer);
        room.timer = null;
    }
    room.timerEnd = null;
}

