wss.on('connection', (ws) => {
    const playerId = uuidv4();
    console.log(`[+] Player connected: ${playerId.substring(0, 8)}`);

    ws.isAlive = true;
    ws.on('pong', () => { ws.isAlive = true; });
    // AFK таймер — 10 минут без активности
    var AFK_TIMEOUT = 10 * 60 * 1000; // 10 минут
    var afkTimer = null;

    function resetAfkTimer() {
        if (afkTimer) clearTimeout(afkTimer);
        afkTimer = setTimeout(function () {
            var info = playerRooms.get(ws);
            if (info) {
                var room = rooms.get(info.roomCode);
                if (room && (room.state === 'lobby')) {
                    // В лобби — кикаем
                    console.log(`[AFK] Kicking idle player from lobby in ${info.roomCode}`);
                    ws.close();
                    return;
                }
            }
            // Если не в комнате (welcome) — просто закрываем
            if (!info) {
                console.log('[AFK] Closing idle connection');
                ws.send(JSON.stringify({ type: 'afkKick', message: 'Вы были отключены из-за неактивности (10 минут)' }));
                setTimeout(function () { ws.close(); }, 1000);
            }
        }, AFK_TIMEOUT);
    }

    resetAfkTimer();
    ws.on('message', (data) => {
        let msg;
        resetAfkTimer(); // Сбрасываем AFK при любой активности
        try { msg = JSON.parse(data.toString()); } catch (e) { return; }

        switch (msg.type) {
            // ==================== СОЗДАНИЕ КОМНАТЫ ====================
            case 'createRoom': {
                const nickname = (msg.nickname || '').trim().substring(0, 20);
                if (!nickname) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Введите никнейм!' }));
                    return;
                }
                const room = createRoom(playerId, msg.settings || {});
                addPlayer(room, playerId, nickname, ws);
                playerRooms.set(ws, { roomCode: room.code, playerId });

                ws.send(JSON.stringify({ type: 'roomCreated', roomCode: room.code, playerId }));
                broadcastToRoom(room, getLobbyState(room));
                console.log(`[ROOM] ${room.code} created by "${nickname}"`);
                break;
            }


            // ==================== БУНКЕР: РАСКРЫТИЕ КАРТЫ ====================
            case 'bunkerReveal': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'bunkerReveal') return;

                var activePlayers = getBunkerActivePlayers(room);
                var currentPlayerId = activePlayers[room.bunker.currentTurnIndex];

                // Только текущий игрок
                if (info.playerId !== currentPlayerId) return;

                // Только одна карта за ход!
                if (room.bunker.hasRevealedThisTurn) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Вы уже раскрыли карту в этом ходу!' }));
                    return;
                }

                var cardKey = msg.cardKey;
                if (!getBunkerCardKeys().includes(cardKey)) return;

                if (room.bunker.revealedCards[info.playerId][cardKey]) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Эта карта уже раскрыта!' }));
                    return;
                }

                room.bunker.hasRevealedThisTurn = true;
                bunkerRevealCard(room, info.playerId, cardKey, false);
                break;
            }

            // ==================== БУНКЕР: ЗАКОНЧИЛ ОБЪЯСНЕНИЕ ====================
            case 'bunkerFinishTurn': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'bunkerReveal') return;

                var activePlayers2 = getBunkerActivePlayers(room);
                var currentId = activePlayers2[room.bunker.currentTurnIndex];

                // Текущий игрок или хост
                if (info.playerId !== currentId && info.playerId !== room.hostId) return;

                clearTimer(room);
                room.bunker.currentTurnIndex++;
                showBunkerCurrentTurn(room);
                break;
            }

            // ==================== БУНКЕР: ГОЛОСОВАНИЕ ====================
            case 'bunkerVote': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'bunkerVote') return;
                if (room.bunker.eliminatedPlayers.includes(info.playerId)) return;

                var targetId2 = msg.targetId; // '__skip__' или playerId
                if (targetId2 !== '__skip__') {
                    if (!room.players.has(targetId2)) return;
                    if (targetId2 === info.playerId) return; // нельзя за себя
                    if (room.bunker.eliminatedPlayers.includes(targetId2)) return;
                }

                room.bunker.votes.set(info.playerId, targetId2);
                ws.send(JSON.stringify({ type: 'bunkerVoteAccepted' }));

                // Прогресс
                var activeCount = 0;
                var votedCount = 0;
                room.players.forEach(p => {
                    if (!room.bunker.eliminatedPlayers.includes(p.id) && p.connected) {
                        activeCount++;
                        if (room.bunker.votes.has(p.id)) votedCount++;
                    }
                });

                broadcastToRoom(room, {
                    type: 'bunkerVoteProgress',
                    voted: votedCount,
                    total: activeCount,
                });

                if (votedCount >= activeCount) {
                    clearTimer(room);
                    processBunkerVotes(room);
                }
                break;
            }

            // ==================== БУНКЕР: ПЕРЕГОЛОСОВАНИЕ ====================
            case 'bunkerTieVote': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'bunkerTieVote') return;
                if (room.bunker.eliminatedPlayers.includes(info.playerId)) return;

                var tieTarget = msg.targetId;
                if (tieTarget !== '__skip__') {
                    if (!room.bunker.tiedPlayers.includes(tieTarget)) return;
                    if (tieTarget === info.playerId) return;
                }

                room.bunker.tieVotes.set(info.playerId, tieTarget);
                ws.send(JSON.stringify({ type: 'bunkerTieVoteAccepted' }));

                var activeCount2 = 0;
                var votedCount2 = 0;
                room.players.forEach(p => {
                    if (!room.bunker.eliminatedPlayers.includes(p.id) && p.connected) {
                        activeCount2++;
                        if (room.bunker.tieVotes.has(p.id)) votedCount2++;
                    }
                });

                broadcastToRoom(room, {
                    type: 'bunkerTieVoteProgress',
                    voted: votedCount2,
                    total: activeCount2,
                });

                if (votedCount2 >= activeCount2) {
                    clearTimer(room);
                    processBunkerTieVotes(room);
                }
                break;
            }

            // ==================== БУНКЕР: ПАУЗА (хост) ====================
            case 'bunkerPause': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || info.playerId !== room.hostId) return;
                if (room.state !== 'bunkerVote' && room.state !== 'bunkerTieVote') return;

                if (room.bunker.paused) {
                    // Unpause — перезапускаем таймер
                    room.bunker.paused = false;
                    var resumeTime = room.state === 'bunkerTieVote' ? 60 : 90;
                    startTimer(room, resumeTime, () => {
                        if (room.state === 'bunkerTieVote') processBunkerTieVotes(room);
                        else processBunkerVotes(room);
                    });
                    broadcastToRoom(room, { type: 'bunkerPauseState', paused: false });
                } else {
                    // Pause
                    room.bunker.paused = true;
                    clearTimer(room);
                    broadcastToRoom(room, { type: 'bunkerPauseState', paused: true });
                }
                break;
            }

            // ==================== ВХОД В КОМНАТУ ====================
            case 'joinRoom': {
                const nickname = (msg.nickname || '').trim().substring(0, 20);
                if (!nickname) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Введите никнейм!' }));
                    return;
                }
                const code = (msg.roomCode || '').toUpperCase().trim();
                const room = rooms.get(code);
                if (!room) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Комната «' + code + '» не найдена. Проверьте код.' }));
                    return;
                }
                if (room.state !== 'lobby') {
                    ws.send(JSON.stringify({ type: 'error', message: 'Игра в этой комнате уже началась.' }));
                    return;
                }
                if (room.players.size >= (room.settings.maxPlayers || 8)) {
                    var maxP = room.settings.maxPlayers || 8;
                    ws.send(JSON.stringify({ type: 'error', message: 'Комната заполнена (максимум ' + maxP + ' игроков).' }));
                    return;
                }
                let nickTaken = false;
                room.players.forEach(p => {
                    if (p.nickname.toLowerCase() === nickname.toLowerCase()) nickTaken = true;
                });
                if (nickTaken) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Никнейм «' + nickname + '» уже занят в этой комнате.' }));
                    return;
                }

                addPlayer(room, playerId, nickname, ws);
                playerRooms.set(ws, { roomCode: room.code, playerId });

                ws.send(JSON.stringify({ type: 'roomJoined', roomCode: room.code, playerId }));
                broadcastToRoom(room, getLobbyState(room));
                console.log(`[JOIN] "${nickname}" joined ${code}`);
                break;
            }

            // ==================== НАСТРОЙКИ ====================
            case 'updateSettings': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.hostId !== info.playerId || room.state !== 'lobby') return;

                const s = msg.settings || {};
                if (s.rounds !== undefined) room.settings.rounds = Math.min(7, Math.max(1, parseInt(s.rounds) || 3));
                if (s.startCapital !== undefined) room.settings.startCapital = Math.min(30, Math.max(3, parseInt(s.startCapital) || 10));
                if (s.useEvents !== undefined) room.settings.useEvents = !!s.useEvents;
                if (s.streamerMode !== undefined) room.settings.streamerMode = !!s.streamerMode;
                if (s.anonymizeParticipants !== undefined) room.settings.anonymizeParticipants = !!s.anonymizeParticipants;
                if (s.useTargetAudience !== undefined) room.settings.useTargetAudience = !!s.useTargetAudience;
                if (s.useHiddenDefects !== undefined) room.settings.useHiddenDefects = !!s.useHiddenDefects;
                if (s.usePackaging !== undefined) room.settings.usePackaging = !!s.usePackaging;
                if (s.bunkerMode !== undefined) room.settings.bunkerMode = !!s.bunkerMode;
                if (s.prepTime !== undefined) room.settings.prepTime = Math.min(600, Math.max(10, parseInt(s.prepTime) || 120));
                if (s.maxPlayers !== undefined) room.settings.maxPlayers = Math.min(18, Math.max(3, parseInt(s.maxPlayers) || 8));
                if (s.presentTime !== undefined) room.settings.presentTime = Math.min(600, Math.max(10, parseInt(s.presentTime) || 120));
                if (s.useReviews !== undefined) room.settings.useReviews = !!s.useReviews;
                if (s.useSpeech !== undefined) room.settings.useSpeech = !!s.useSpeech;
                if (s.investTime !== undefined) room.settings.investTime = Math.min(600, Math.max(10, parseInt(s.investTime) || 60));
                if (s.pseudoMode !== undefined) room.settings.pseudoMode = !!s.pseudoMode;
                if (s.modifier !== undefined) {
                    var mod = s.modifier;
                    if (mod === 'addition' || mod === 'metaphor') {
                        room.settings.modifier = mod;
                        // Модификаторы несовместимы с генератором абсурда
                        if (room.settings.cardSource === 'players') {
                            room.settings.cardSource = 'database';
                        }
                    } else {
                        room.settings.modifier = 'none';
                    }
                }
                if (s.blackSwan !== undefined) {
                    room.settings.blackSwan = !!s.blackSwan;
                    if (room.settings.blackSwan && room.settings.cardSource === 'players') {
                        room.settings.cardSource = 'database';
                    }
                }
                if (s.cardSource !== undefined) {
                    room.settings.cardSource = (s.cardSource === 'players') ? 'players' : 'database';
                    if (room.settings.cardSource === 'players') {
                        room.settings.blackSwan = false;
                        room.settings.modifier = 'none';
                    }
                }
                if (!room.settings.streamerMode) {
                    room.settings.anonymizeParticipants = false;
                }
                room.totalRounds = room.settings.rounds;

                broadcastToRoom(room, getLobbyState(room));
                break;
            }

            // ==================== СТАРТ ИГРЫ ====================
            case 'startGame': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.hostId !== info.playerId || room.state !== 'lobby') return;
                if (room.players.size < 3) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Нужно минимум 3 игрока!' }));
                    return;
                }
                console.log(`[GAME] Starting in room ${room.code} with ${room.players.size} players`);

                if (room.settings.bunkerMode) {
                    startBunkerGame(room);
                } else {
                    startGame(room);
                }
                break;
            }
            case 'playerReady': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'preparation') return;

                const player = room.players.get(info.playerId);
                if (!player) return;

                player.isReady = true;

                // Сохраняем текст если пришёл
                if (msg.text !== undefined) {
                    player.pitchText = (msg.text || '').substring(0, 7000);
                }

                let readyCount = 0;
                let totalCount = 0;
                room.players.forEach(p => {
                    totalCount++;
                    if (p.isReady) readyCount++;
                });

                broadcastToRoom(room, {
                    type: 'readyProgress',
                    ready: readyCount,
                    total: totalCount,
                });

                console.log(`[READY] ${player.nickname} ready (${readyCount}/${totalCount}) in ${room.code}`);

                // Если все готовы — переходим к презентациям
                if (readyCount >= totalCount) {
                    console.log(`[READY] All players ready in ${room.code}, starting presentations`);
                    clearTimer(room);
                    startPresentations(room);
                }
                break;
            }
            case 'tiebreakerReady': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'tiebreaker_prep') return;

                const player = room.players.get(info.playerId);
                if (!player) return;

                // Проверяем что этот игрок участвует в ничье
                if (!room.tiedPlayers.includes(info.playerId)) return;

                // Сохраняем текст
                if (msg.text !== undefined) {
                    player.pitchText = (msg.text || '').substring(0, 7000);
                }

                // Помечаем готовность
                player.tbReady = true;

                // Считаем готовых среди участников ничьи
                let tbReadyCount = 0;
                let tbTotalCount = room.tiedPlayers.length;
                room.tiedPlayers.forEach(id => {
                    const p = room.players.get(id);
                    if (p && p.tbReady) tbReadyCount++;
                });

                // Подтверждение отправителю
                ws.send(JSON.stringify({ type: 'tiebreakerReadyAccepted' }));

                // Прогресс всем
                broadcastToRoom(room, {
                    type: 'tiebreakerReadyProgress',
                    ready: tbReadyCount,
                    total: tbTotalCount,
                });

                console.log(`[TB-READY] ${player.nickname} ready (${tbReadyCount}/${tbTotalCount}) in ${room.code}`);

                // Если все участники ничьи готовы — начинаем выступления
                if (tbReadyCount >= tbTotalCount) {
                    console.log(`[TB-READY] All tied players ready in ${room.code}, starting tiebreaker`);
                    clearTimer(room);
                    startTiebreaker(room);
                }
                break;
            }
            // ==================== СЛЕДУЮЩИЙ ПРЕЗЕНТЕР ====================
            case 'nextPresenter': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'presentation') return;
                // Только хост может переключать выступающих
                if (info.playerId !== room.hostId) return;
                nextPresenter(room);
                break;
            }

            // ==================== ИНВЕСТИЦИИ ====================
            case 'kickPlayer': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.hostId !== info.playerId) return;

                const targetId = msg.targetPlayerId;
                if (!targetId || targetId === room.hostId) return;
                const target = room.players.get(targetId);
                if (!target) return;

                room.players.delete(targetId);
                room.presentationOrder = (room.presentationOrder || []).filter(id => id !== targetId);
                room.tiedPlayers = (room.tiedPlayers || []).filter(id => id !== targetId);
                if (room.investments) {
                    room.investments.delete(targetId);
                    room.investments.forEach((arr, investorId) => {
                        room.investments.set(investorId, (arr || []).filter(inv => inv.targetId !== targetId));
                    });
                }

                const dTimer = disconnectTimers.get(targetId);
                if (dTimer) {
                    clearTimeout(dTimer);
                    disconnectTimers.delete(targetId);
                }

                if (target.ws && target.ws.readyState === WebSocket.OPEN) {
                    playerRooms.delete(target.ws);
                    target.ws.send(JSON.stringify({ type: 'kicked', message: 'Хост исключил вас из комнаты.' }));
                    setTimeout(() => {
                        try { target.ws.close(); } catch (e) { /* ignore */ }
                    }, 100);
                }

                broadcastToRoom(room, {
                    type: 'playerDisconnected',
                    playerId: targetId,
                    nickname: target.nickname,
                    message: 'Игрок исключен хостом',
                    players: getPlayersPublicInfo(room),
                });

                if (room.state === 'lobby') {
                    broadcastToRoom(room, getLobbyState(room));
                } else if (room.state === 'investing') {
                    room.investmentCaps = getInvestmentCaps(room);
                    const allPresentations = room.presentationOrder.map(id => {
                        const p = room.players.get(id);
                        return (p && !p.eliminated) ? {
                            id,
                            nickname: getDisplayNickname(room, id),
                            cards: p.cards,
                            pitchText: p.pitchText || '',
                        } : null;
                    }).filter(Boolean);

                    broadcastToRoom(room, {
                        type: 'investingPhase',
                        phase: 'investing',
                        players: getPlayersPublicInfo(room),
                        presentations: allPresentations,
                        event: room.currentEvent,
                        investTime: room.settings.investTime,
                        investmentCaps: room.investmentCaps,
                        round: room.currentRound,
                        totalRounds: room.totalRounds,
                    });
                    broadcastToRoom(room, {
                        type: 'investmentProgress',
                        voted: room.investments.size,
                        total: room.players.size,
                    });

                    if (room.investments.size >= room.players.size) {
                        clearTimer(room);
                        processInvestments(room);
                    }
                }
                break;
            }

            case 'submitInvestment': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'investing') return;

                const player = room.players.get(info.playerId);
                if (!player) return;

                const investments = msg.investments || [];
                let total = 0;
                const validInvestments = [];

                for (const inv of investments) {
                    const amount = parseInt(inv.amount) || 0;
                    if (amount > 0 && inv.targetId !== info.playerId && room.players.has(inv.targetId)) {
                        validInvestments.push({ targetId: inv.targetId, amount });
                        total += amount;
                    }
                }

                if (total > player.capital) {
                    ws.send(JSON.stringify({ type: 'error', message: 'Недостаточно капитала! У вас ' + player.capital + ', пытаетесь вложить ' + total }));
                    return;
                }
                const capLimit = room.investmentCaps && room.investmentCaps[info.playerId] !== undefined
                    ? room.investmentCaps[info.playerId]
                    : player.capital;
                if (total > capLimit) {
                    ws.send(JSON.stringify({
                        type: 'error',
                        message: 'Лимит инвестиций на этот раунд: ' + capLimit + '. Уменьшите сумму.',
                    }));
                    return;
                }

                room.investments.set(info.playerId, validInvestments);
                ws.send(JSON.stringify({ type: 'investmentAccepted', total }));

                broadcastToRoom(room, {
                    type: 'investmentProgress',
                    voted: room.investments.size,
                    total: room.players.size,
                });
                // Если все проголосовали — автоматически переходим
                if (room.investments.size >= room.players.size) {
                    console.log(`[INVEST] All players invested in ${room.code}, processing`);
                    clearTimer(room);
                    processInvestments(room);
                }
                break;
            }

            // ==================== ТАЙБРЕЙКЕР ГОЛОСОВАНИЕ ====================
            case 'submitTieInvestment': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'tiebreaker_voting') return;

                const investments = msg.investments || [];
                const validInvestments = [];
                for (const inv of investments) {
                    const amount = parseInt(inv.amount) || 0;
                    if (amount > 0 && room.tiedPlayers.includes(inv.targetId) && inv.targetId !== info.playerId) {
                        validInvestments.push({ targetId: inv.targetId, amount });
                    }
                }
                room.tieInvestments.set(info.playerId, validInvestments);
                ws.send(JSON.stringify({ type: 'tieInvestmentAccepted' }));

                broadcastToRoom(room, {
                    type: 'tieVoteProgress',
                    voted: room.tieInvestments.size,
                    total: room.players.size,
                });
                // Если все проголосовали — автоматически переходим
                if (room.tieInvestments.size >= room.players.size) {
                    console.log(`[TIEVOTE] All players voted in ${room.code}, processing`);
                    clearTimer(room);
                    processTiebreaker(room);
                }
                break;
            }

            // ==================== СЛЕДУЮЩИЙ РАУНД ====================
            case 'nextRound': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.hostId !== info.playerId || room.state !== 'roundResults') return;

                if (room.currentRound >= room.totalRounds) {
                    showFinalResults(room);
                } else {
                    startNewRound(room);
                }
                break;
            }

            // ==================== ТАЙБРЕЙКЕР — СЛЕДУЮЩИЙ ====================
            case 'nextTiebreakerPresenter': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'tiebreaker') return;
                if (info.playerId !== room.hostId) return;
                clearTimer(room);
                room.currentPresenterIndex++;
                showTiebreakerPresenter(room);
                break;
            }

            // ==================== ИГРАТЬ ЗАНОВО ====================
            case 'playAgain': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.hostId !== info.playerId) return;

                room.state = 'lobby';
                room.currentRound = 0;
                room.roundHistory = [];
                room.decks = {
                    adjectives: shuffle([...Array(ADJECTIVES.length).keys()]),
                    items: shuffle([...Array(ITEMS.length).keys()]),
                    features: shuffle([...Array(FEATURES.length).keys()]),
                    events: shuffle([...EVENTS]),
                    reviews: shuffle([...Array(REVIEWS.length).keys()]),
                    additions: shuffle([...Array(ADDITIONS.length).keys()]),
                    targetAudience: shuffle([...Array(TARGET_AUDIENCE.length).keys()]),
                    hiddenDefects: shuffle([...Array(HIDDEN_DEFECTS.length).keys()]),
                    packaging: shuffle([...Array(PACKAGING.length).keys()]),
                };
                room.players.forEach(p => {
                    p.capital = room.settings.startCapital;
                    p.attractedInvestments = 0;
                    p.cards = null;
                    p.eliminated = false;  // ← ДОБАВЬ ЭТО

                });
                room.anonAliases = {};
                room.bunker = {
                    enabled: false,
                    globalProblem: null,
                    revealOrder: [],
                    currentTurnIndex: 0,
                    currentRound: 0,
                    eliminatedPlayers: [],
                    revealedCards: {},
                    votes: new Map(),
                    tiedPlayers: [],
                    tieVotes: new Map(),
                    survivorsCount: 0,
                    totalPlayers: 0,
                    paused: false,
                };
                broadcastToRoom(room, getLobbyState(room));
                break;
            }

            // ==================== ПОЛЬЗОВАТЕЛЬСКИЕ КАРТЫ ====================
            case 'submitCustomCard': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.state !== 'cardInput') return;

                const player = room.players.get(info.playerId);
                if (!player) return;

                var cardType = room.currentCardInputType;
                var mapKeyMap = {
                    adjective: 'adjectives',
                    item: 'items',
                    feature: 'features',
                    review: 'reviews',
                    targetAudience: 'targetAudience',
                    hiddenDefect: 'hiddenDefects',
                    packaging: 'packaging',
                };
                var mapKey = mapKeyMap[cardType] || 'adjectives';

                // Не принимаем повторно
                if (room.customCards[mapKey].has(info.playerId)) return;

                var text = (msg.text || '').trim().substring(0, 120);
                room.customCards[mapKey].set(info.playerId, text || null);

                ws.send(JSON.stringify({ type: 'cardSubmitAccepted' }));

                // Прогресс
                broadcastToRoom(room, {
                    type: 'cardInputProgress',
                    submitted: room.customCards[mapKey].size,
                    total: room.players.size,
                });

                console.log(`[CARD] "${player.nickname}" submitted ${cardType}: "${text}" in ${room.code}`);

                // Если все отправили — переходим
                if (room.customCards[mapKey].size >= room.players.size) {
                    processCardInputPhase(room);
                }
                break;
            }

            // ==================== ОЗВУЧКА ====================
            case 'triggerSpeech': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room) return;
                if (info.playerId !== room.hostId) return;
                if (!room.settings.useSpeech) return;

                // Пересылаем всем игрокам команду озвучить
                broadcastToRoom(room, {
                    type: 'playSpeech',
                    texts: msg.texts || [],
                });
                break;
            }

            // ==================== СТРИМЕРСКИЙ РЕЖИМ: ТЕКСТ ПРЕЗЕНТАЦИИ ====================
            case 'updatePitchText': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room) return;
                // Разрешаем обновлять текст в подготовке, тайбрейкере и при ничье
                const allowedStates = ['preparation', 'presentation', 'tiebreaker_prep', 'tiebreaker'];
                if (!allowedStates.includes(room.state)) return;
                const player = room.players.get(info.playerId);
                if (!player) return;
                player.pitchText = (msg.text || '').substring(0, 7000);
                break;
            }

            // ==================== ПРОПУСК ТАЙМЕРА (хост) ====================
            case 'skipTimer': {
                const info = playerRooms.get(ws);
                if (!info) return;
                const room = rooms.get(info.roomCode);
                if (!room || room.hostId !== info.playerId) return;

                if (room.timer) {
                    clearTimeout(room.timer);
                    room.timer = null;

                    switch (room.state) {
                        case 'preparation':
                            // В стримерском режиме нельзя скипать подготовку кнопкой
                            if (room.settings.streamerMode) {
                                ws.send(JSON.stringify({ type: 'error', message: 'В стримерском режиме подготовка завершается когда все готовы или по таймеру' }));
                                // Перезапускаем таймер на оставшееся время
                                const remaining = Math.max(1, Math.ceil((room.timerEnd - Date.now()) / 1000));
                                startTimer(room, remaining, () => {
                                    startPresentations(room);
                                });
                                return;
                            }
                            startPresentations(room);
                            break;
                        case 'investing':
                            processInvestments(room);
                            break;
                    }
                }
                break;
            }
        }
    });

    // ==================== ОТКЛЮЧЕНИЕ ====================
    ws.on('close', () => {
        if (afkTimer) { clearTimeout(afkTimer); afkTimer = null; }
        const info = playerRooms.get(ws);
        if (info) {
            const room = rooms.get(info.roomCode);
            if (room) {
                const player = room.players.get(info.playerId);
                if (player) {
                    player.connected = false;
                    player.ws = null;
                    console.log(`[-] "${player.nickname}" disconnected from ${room.code}`);

                    if (room.state === 'lobby') {
                        // В лобби — просто удаляем
                        room.players.delete(info.playerId);
                        if (room.players.size === 0) {
                            clearTimer(room);
                            rooms.delete(room.code);
                            console.log(`[ROOM] ${room.code} deleted (empty)`);
                        } else {
                            if (room.hostId === info.playerId) {
                                const first = room.players.values().next().value;
                                if (first) {
                                    room.hostId = first.id;
                                    first.isHost = true;
                                }
                            }
                            broadcastToRoom(room, getLobbyState(room));
                        }
                    } else {
                        // Во время игры — даём 15 сек на возврат
                        broadcastToRoom(room, {
                            type: 'playerDisconnected',
                            playerId: info.playerId,
                            nickname: player.nickname,
                            players: getPlayersPublicInfo(room),
                        });

                        const timerId = setTimeout(() => {
                            disconnectTimers.delete(info.playerId);
                            const currentRoom = rooms.get(info.roomCode);
                            if (currentRoom) {
                                handlePlayerTimeout(currentRoom, info.playerId);
                            }
                        }, RECONNECT_TIMEOUT);

                        disconnectTimers.set(info.playerId, timerId);
                    }
                }
            }
            playerRooms.delete(ws);
        }
    });
});

